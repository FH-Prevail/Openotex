// electron-builder afterPack hook. On Linux, Openotex starts through a small
// shell launcher that decides whether Chromium's sandbox can work.
//
// An AppImage cannot ship the setuid chrome-sandbox helper, so Electron needs
// unprivileged user namespaces. Ubuntu 24.04+ restricts them with AppArmor,
// some kernels or container profiles block them, and Chromium refuses to run
// as root with the sandbox. Only in those cases does the launcher add --no-sandbox (without it
// the app aborts at start-up); everywhere else the sandbox stays on.
const fs = require('fs');
const path = require('path');

const launcher = binaryName => `#!/bin/sh
# Openotex launcher (generated by scripts/linux-after-pack.js).
HERE=$(dirname "$(readlink -f "$0")")
BIN="$HERE/${binaryName}"

# With ELECTRON_RUN_AS_NODE the binary is plain Node.js (the MCP server),
# which does not accept Chromium switches.
if [ -z "$ELECTRON_RUN_AS_NODE" ]; then
  no_sandbox=0
  if [ "$(id -u)" = "0" ]; then
    no_sandbox=1
  elif [ "$(cat /proc/sys/kernel/apparmor_restrict_unprivileged_userns 2>/dev/null)" = "1" ]; then
    no_sandbox=1
  elif [ "$(cat /proc/sys/kernel/unprivileged_userns_clone 2>/dev/null)" = "0" ]; then
    no_sandbox=1
  elif [ "$(cat /proc/sys/user/max_user_namespaces 2>/dev/null)" = "0" ]; then
    no_sandbox=1
  elif command -v unshare >/dev/null 2>&1 && ! unshare -Ur true >/dev/null 2>&1; then
    # Blocked some other way (seccomp in containers, LSM policies).
    no_sandbox=1
  fi
  if [ "$no_sandbox" = "1" ]; then
    exec "$BIN" --no-sandbox "$@"
  fi
fi
exec "$BIN" "$@"
`;

exports.default = async function afterPack(context) {
  if (context.electronPlatformName !== 'linux') {
    return;
  }
  const executableName = context.packager.executableName;
  const executable = path.join(context.appOutDir, executableName);
  const binaryName = `${executableName}.bin`;
  fs.renameSync(executable, path.join(context.appOutDir, binaryName));
  fs.writeFileSync(executable, launcher(binaryName), { mode: 0o755 });
  fs.chmodSync(executable, 0o755);
  console.log(`  • Linux launcher written: ${executableName} -> ${binaryName}`);
};
